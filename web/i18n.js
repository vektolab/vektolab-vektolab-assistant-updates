function vkResolveI18nKey(raw, aliasMap) {
  var n = normalizeCatKey(raw);
  if (!n) return null;
  if (aliasMap[n]) return aliasMap[n];
  // también acepta claves ya normalizadas tipo "cat_general"
  if (raw && typeof raw === "string" && aliasMap[String(raw).toLowerCase()]) {
    return aliasMap[String(raw).toLowerCase()];
  }
  return null;
}

/** Devuelve la etiqueta de categoría en el idioma activo (diccionario).
 *  Si no hay alias conocido, devuelve null (el caller puede usar Google).
 */
function vkCategoryLabel(raw) {
  var key = vkResolveI18nKey(raw, CAT_ALIASES);
  if (!key) return null;
  if (typeof t === "function") {
    var v = t(key);
    if (v && v !== key) return v;
  }
  return null;
}

function vkSubcategoryLabel(raw) {
  var key = vkResolveI18nKey(raw, SUB_ALIASES);
  if (!key) return null;
  if (typeof t === "function") {
    var v = t(key);
    if (v && v !== key) return v;
  }
  return null;
}

