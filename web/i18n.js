var _vkI18nResolve;
window.vkI18nReady = new Promise(function (resolve) { _vkI18nResolve = resolve; });
window.ensureLangTranslations = ensureLangTranslations;
window.t = t;
window.getLang = getLang;
window.setLang = setLang;
window.applyI18nDom = applyI18nDom;


/** Mapea categoría/subcategoría de la API (suele venir en español) a clave i18n.
 *  Así "General", "Decoración", etc. salen bien en TODOS los idiomas del
 *  diccionario, sin depender de Google Translate (como ya ocurre en japonés
 *  cuando la API de traducción responde bien).
 */
function normalizeCatKey(value) {
  return String(value || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

