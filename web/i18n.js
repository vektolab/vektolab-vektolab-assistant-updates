function bootI18n() {
  applyI18nDom();
  var done = function () {
    applyI18nDom();
    document.dispatchEvent(new CustomEvent("vk-lang-ready", { detail: { lang: currentLang } }));
    document.dispatchEvent(new CustomEvent("vk-lang-changed", { detail: { lang: currentLang, phase: "ready" } }));
    if (_vkI18nResolve) { _vkI18nResolve(currentLang); _vkI18nResolve = null; }
  };
  ensureLangTranslations(currentLang).then(done).catch(done);
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", bootI18n);
} else {
  bootI18n();
}
